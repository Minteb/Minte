  function tint(hex, amt) { // mix a hex colour with white (amt 0..1)
    var n = parseInt(hex.slice(1), 16), r = n >> 16, g = (n >> 8) & 255, b = n & 255;
    var m = function (c) { return Math.round(c + (255 - c) * amt); };
    return "rgb(" + m(r) + "," + m(g) + "," + m(b) + ")";
  }
