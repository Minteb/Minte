  var zoneAreaCache = {};
  function zoneArea(region, zone) {
    var k = zkey(region, zone);
    if (zoneAreaCache[k]) return zoneAreaCache[k];
    // approximate: sum of all woreda areas is not shipped for non-Lersha woredas; use polygon area on sphere
    var l = featureIndex.zone[k];
    var a = l ? geoArea(l.feature.geometry) : 0;
    zoneAreaCache[k] = a;
    return a;
  }
  function geoArea(g) { // spherical polygon area in km² (good to ~1%)
    var R = 6371.0088, rad = Math.PI / 180;
    var ring = function (c) {
      var s = 0;
      for (var i = 0; i < c.length - 1; i++) s += (c[i + 1][0] - c[i][0]) * rad * (2 + Math.sin(c[i][1] * rad) + Math.sin(c[i + 1][1] * rad));
      return Math.abs(s * R * R / 2);
    };
    var poly = function (p) { return p.reduce(function (s, r, i) { return s + (i ? -ring(r) : ring(r)); }, 0); };
    if (g.type === "Polygon") return poly(g.coordinates);
    if (g.type === "MultiPolygon") return g.coordinates.reduce(function (s, p) { return s + poly(p); }, 0);
    return 0;
  }

  function countBy(list, keyFn) {
    var o = {};
    list.forEach(function (r) { var k = keyFn(r); o[k] = (o[k] || 0) + 1; });
    return Object.keys(o).map(function (k) { return { k: k, n: o[k] }; }).sort(function (a, b) { return b.n - a.n || a.k.localeCompare(b.k); });
  }

