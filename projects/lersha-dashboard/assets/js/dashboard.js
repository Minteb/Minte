  function csv(list, cols) {
    var q = function (v) { v = v == null ? "" : String(v); return /[",\n]/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v; };
    return "\ufeff" + cols.join(",") + "\n" + list.map(function (r) { return cols.map(function (c) { return q(r[c]); }).join(","); }).join("\n");
  }
